-- 1. SECUENCIAS
CREATE SEQUENCE seq_club
START WITH 703
INCREMENT BY 4
NOCACHE;

-- 2. TABLAS INDEPENDIENTES
CREATE TABLE region (
    id_region NUMBER(3) NOT NULL,
    nombre VARCHAR2(50) NOT NULL,
    CONSTRAINT region_pk PRIMARY KEY (id_region)
);

CREATE TABLE nacionalidad (
    id_nacionalidad NUMBER(5) GENERATED BY DEFAULT AS IDENTITY (START WITH 210 INCREMENT BY 2),
    descripcion VARCHAR2(50) NOT NULL,
    CONSTRAINT nacionalidad_pk PRIMARY KEY (id_nacionalidad)
);

CREATE TABLE asociacion (
    id_asociacion NUMBER(5) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    fecha_creacion DATE NOT NULL,
    tipo CHAR(1) NOT NULL,
    CONSTRAINT asociacion_pk PRIMARY KEY (id_asociacion),
    CONSTRAINT asociacion_fecha_ck CHECK (fecha_creacion >= TO_DATE('31-12-1980', 'DD-MM-YYYY')),
    CONSTRAINT asociacion_tipo_ck CHECK (tipo IN ('P', 'A'))
);

CREATE TABLE club_futbol (
    id_club NUMBER(5) NOT NULL,
    nombre_club VARCHAR2(100) NOT NULL,
    patrimonio NUMBER(15) NOT NULL,
    ubicacion_calle VARCHAR2(150),
    tipo_club VARCHAR2(20) NOT NULL,
    CONSTRAINT club_futbol_pk PRIMARY KEY (id_club),
    CONSTRAINT club_futbol_nombre_un UNIQUE (nombre_club),
    CONSTRAINT club_futbol_tipo_ck CHECK (tipo_club IN ('Profesional', 'Amateur'))
);

CREATE TABLE escuela_futbol (
    id_escuela NUMBER(5) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    capacidad NUMBER(5),
    fecha_fundacion DATE,
    CONSTRAINT escuela_futbol_pk PRIMARY KEY (id_escuela)
);

CREATE TABLE idioma (
    id_idioma NUMBER(3) NOT NULL,
    nombre_idioma VARCHAR2(50) NOT NULL,
    CONSTRAINT idioma_pk PRIMARY KEY (id_idioma)
);

-- 3. TABLAS DEPENDIENTES
CREATE TABLE comuna (
    id_comuna NUMBER(5) NOT NULL,
    id_region NUMBER(3) NOT NULL,
    nombre VARCHAR2(50) NOT NULL,
    CONSTRAINT comuna_pk PRIMARY KEY (id_comuna),
    CONSTRAINT comuna_region_fk FOREIGN KEY (id_region) REFERENCES region(id_region)
);

CREATE TABLE trabajador (
    id_trabajador NUMBER(10) NOT NULL,
    rut NUMBER(8) NOT NULL,
    dv CHAR(1) NOT NULL,
    nombres VARCHAR2(50) NOT NULL,
    apellidos VARCHAR2(50) NOT NULL,
    sueldo_base NUMBER(12) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    genero CHAR(1) NOT NULL,
    estado_civil VARCHAR2(20) NOT NULL,
    telefono_movil VARCHAR2(15),
    direccion VARCHAR2(150),
    id_comuna NUMBER(5) NOT NULL,
    id_nacionalidad NUMBER(5) NOT NULL,
    tipo_trabajador VARCHAR2(20) NOT NULL,
    CONSTRAINT trabajador_pk PRIMARY KEY (id_trabajador),
    CONSTRAINT trabajador_rut_un UNIQUE (rut, dv),
    CONSTRAINT trabajador_comuna_fk FOREIGN KEY (id_comuna) REFERENCES comuna(id_comuna),
    CONSTRAINT trabajador_nacionalidad_fk FOREIGN KEY (id_nacionalidad) REFERENCES nacionalidad(id_nacionalidad),
    CONSTRAINT trabajador_genero_ck CHECK (genero IN ('M', 'F', 'O')),
    CONSTRAINT trabajador_tipo_ck CHECK (tipo_trabajador IN ('JUGADOR', 'PERSONAL_PLANTA'))
);

CREATE TABLE jugador (
    id_trabajador NUMBER(10) NOT NULL,
    puesto VARCHAR2(30) NOT NULL,
    monto_premios NUMBER(15) DEFAULT 0,
    id_asociacion NUMBER(5) NOT NULL,
    id_escuela NUMBER(5),
    anio_fin_amateur NUMBER(4),
    CONSTRAINT jugador_pk PRIMARY KEY (id_trabajador),
    CONSTRAINT jugador_trabajador_fk FOREIGN KEY (id_trabajador) REFERENCES trabajador(id_trabajador),
    CONSTRAINT jugador_asociacion_fk FOREIGN KEY (id_asociacion) REFERENCES asociacion(id_asociacion),
    CONSTRAINT jugador_escuela_fk FOREIGN KEY (id_escuela) REFERENCES escuela_futbol(id_escuela)
);

CREATE TABLE personal_planta (
    id_trabajador NUMBER(10) NOT NULL,
    horas_trabajadas NUMBER(5),
    valor_horas_extras NUMBER(10),
    CONSTRAINT personal_planta_pk PRIMARY KEY (id_trabajador),
    CONSTRAINT personal_planta_trabajador_fk FOREIGN KEY (id_trabajador) REFERENCES trabajador(id_trabajador)
);

CREATE TABLE contrato (
    id_contrato NUMBER(10) NOT NULL,
    id_trabajador NUMBER(10) NOT NULL,
    id_club NUMBER(5) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    CONSTRAINT contrato_pk PRIMARY KEY (id_contrato),
    CONSTRAINT contrato_trabajador_fk FOREIGN KEY (id_trabajador) REFERENCES trabajador(id_trabajador),
    CONSTRAINT contrato_club_fk FOREIGN KEY (id_club) REFERENCES club_futbol(id_club)
);

CREATE TABLE jugador_idioma (
    id_trabajador NUMBER(10) NOT NULL,
    id_idioma NUMBER(3) NOT NULL,
    nivel_dominio VARCHAR2(20) NOT NULL,
    CONSTRAINT jugador_idioma_pk PRIMARY KEY (id_trabajador, id_idioma),
    CONSTRAINT jugador_idioma_trabajador_fk FOREIGN KEY (id_trabajador) REFERENCES jugador(id_trabajador),
    CONSTRAINT jugador_idioma_idioma_fk FOREIGN KEY (id_idioma) REFERENCES idioma(id_idioma)
);

